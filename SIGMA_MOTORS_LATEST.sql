CREATE DATABASE IF NOT EXISTS SIGMA_MOTORS;
USE SIGMA_MOTORS;

--  TABLE 1: BRANDS

CREATE TABLE BRANDS
(
BRAND_ID INT PRIMARY KEY AUTO_INCREMENT,
BRAND_NAME VARCHAR(50) NOT NULL,
COUNTRY_OF_ORIGIN VARCHAR(50),
IS_ACTIVE BOOL NOT NULL
);
--  TABLE 2: MODELS

CREATE TABLE MODELS
(
MODEL_ID INT PRIMARY KEY AUTO_INCREMENT,
BRAND_ID INT,
MODEL_NAME VARCHAR(50) NOT NULL,
BODY_TYPE VARCHAR(50),
ENGINE_DISPLACEMENT INT,
IS_ACTIVE BOOL NOT NULL,
FOREIGN KEY (BRAND_ID) REFERENCES BRANDS(BRAND_ID)
);
--  TABLE 3: VARIENTS

CREATE TABLE VARIENTS
(
VARIENT_ID INT PRIMARY KEY AUTO_INCREMENT,
MODEL_ID INT,
VARIENT_NAME VARCHAR(50),
TRANSMISSION_TYPE VARCHAR(50),
FUEL_TYPE VARCHAR(50),
IS_ACTIVE BOOL NOT NULL,
FOREIGN KEY (MODEL_ID) REFERENCES MODELS(MODEL_ID)
);
--  TABLE 4: VEHICLE

CREATE TABLE VEHICLE
(
VEHICLE_ID INT PRIMARY KEY AUTO_INCREMENT,
BRAND_ID INT,
MODEL_ID INT,
VARIENT_ID INT,
REGISTRATION_NUMBER VARCHAR(20) UNIQUE,
COLOUR VARCHAR(20),
MANUFACTURE_YEAR YEAR,
PRICE DECIMAL(10,2) NOT NULL,   
STATUS VARCHAR(50),
FOREIGN KEY (BRAND_ID) REFERENCES BRANDS(BRAND_ID),
FOREIGN KEY (MODEL_ID) REFERENCES MODELS(MODEL_ID),
FOREIGN KEY (VARIENT_ID) REFERENCES VARIENTS(VARIENT_ID)
);
--  TABLE 5: EMPLOYEE

CREATE TABLE EMPLOYEE
(
EMPLOYEE_ID INT PRIMARY KEY AUTO_INCREMENT,
NAME VARCHAR(50),
CNIC VARCHAR(13)  UNIQUE NOT NULL,
ROLE VARCHAR(20),
LOGIN_ID VARCHAR(50)  UNIQUE NOT NULL,
PASSWORD VARCHAR(50)  NOT NULL,
IS_ACTIVE BOOL
);

