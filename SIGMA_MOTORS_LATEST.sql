--  TABLE 6: CUSTOMER

CREATE TABLE CUSTOMER
(
CUSTOMER_ID  INT PRIMARY KEY AUTO_INCREMENT,
NAME VARCHAR(50),
CNIC VARCHAR(13)  UNIQUE NOT NULL,
PHONE_NUMBER VARCHAR(11)  NOT NULL,
EMAIL VARCHAR(255),
ADDRESS VARCHAR(50),
CONSTRAINT CHECK_EMAIL_FORMAT CHECK (EMAIL LIKE '%_@__%.__%')
);
--  TABLE 7: SUPPLIER

CREATE TABLE SUPPLIER
(
SUPPLIER_ID  INT PRIMARY KEY AUTO_INCREMENT,
COMPANY_NAME VARCHAR(50) UNIQUE NOT NULL,
PHONE_NUMBER VARCHAR(11) NOT NULL,
NTN VARCHAR(20),
ADDRESS VARCHAR(50),
IS_ACTIVE BOOL
);
--  TABLE 8: PURCHASE_ORDERS

CREATE TABLE PURCHASE_ORDERS
(
PURCHASE_ORDER_ID INT PRIMARY KEY AUTO_INCREMENT,
VEHICLE_ID INT,
SUPPLIER_ID INT,
EMPLOYEE_ID INT,
PRICE DECIMAL(10,2) NOT NULL,
PURCHASE_DATE DATE,
STATUS VARCHAR(20),
FOREIGN KEY (VEHICLE_ID)  REFERENCES VEHICLE(VEHICLE_ID),
FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIER(SUPPLIER_ID),
FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);
--  TABLE 9: SALE_TRANSCTION

CREATE TABLE SALE_TRANSCTION
(
SALE_ID INT PRIMARY KEY AUTO_INCREMENT,
VEHICLE_ID INT,
CUSTOMER_ID INT,
EMPLOYEE_ID INT,
EMPLOYEE_NAME VARCHAR(100),
PRICE DECIMAL(10,2),
DISCOUNT DECIMAL(10,2) DEFAULT 0,
SALE_DATE DATE,
PAYMENT_STATUS VARCHAR(50),
PAYMENT_METHOD VARCHAR(50),
FOREIGN KEY (VEHICLE_ID)  REFERENCES VEHICLE(VEHICLE_ID),
FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);
--  TABLE 10: GATE_PASSES

CREATE TABLE GATE_PASSES
(
    GATE_PASS_ID INT PRIMARY KEY AUTO_INCREMENT,
    VEHICLE_ID   INT,
    SALE_ID      INT,
    EMPLOYEE_ID  INT,
    TIMESTAMP    DATETIME,
    QR_DATA      VARCHAR(50)
);
--  TABLE 11: HARDWARE_AUDIT_LOGS

CREATE TABLE HARDWARE_AUDIT_LOGS
(
LOG_ID INT PRIMARY KEY AUTO_INCREMENT,
EMPLOYEE_ID INT,
VEHICLE_ID INT,
LOG_TYPE VARCHAR(50),
DEVICE_ID INT,
EVENT_DATA VARCHAR(50)
);
--  TABLE 12: INVOICES  (new table)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE INVOICES
(
INVOICE_ID INT PRIMARY KEY AUTO_INCREMENT,
SALE_ID INT NOT NULL,
CUSTOMER_ID INT NOT NULL,
VEHICLE_ID INT NOT NULL,
EMPLOYEE_ID INT NOT NULL,
INVOICE_DATE DATE NOT NULL,
TOTAL_AMOUNT DECIMAL(12,2) NOT NULL,
DISCOUNT DECIMAL(12,2) DEFAULT 0,
NET_AMOUNT DECIMAL(12,2) NOT NULL,
STATUS VARCHAR(50) DEFAULT 'Payment Pending',
CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
FOREIGN KEY (SALE_ID) REFERENCES SALE_TRANSCTION(SALE_ID),
FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
FOREIGN KEY (VEHICLE_ID)  REFERENCES VEHICLE(VEHICLE_ID),
FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

